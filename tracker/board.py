#!/usr/bin/env python3
"""Tracker: board generator and ticket editor.

    board.py                          regenerate BOARD.md
    board.py status FM-001 ready      set a ticket's status, then regenerate
    board.py set FM-001 points 3      set any editable field, then regenerate
    board.py ls [status]              list tickets, optionally filtered

The markdown files in tickets/ are the source of truth. BOARD.md is generated.
No third-party dependencies on purpose - this must run on a bare Python 3.
"""

from __future__ import annotations

import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TICKETS_DIR = ROOT / "tickets"
BOARD_FILE = ROOT / "BOARD.md"

STATUSES = ["in-progress", "in-review", "ready", "blocked", "backlog", "done"]
TYPES = ["story", "task", "spike", "bug"]
EPICS = ["auth", "expense", "investment", "analytics",
         "platform", "observability", "security"]

FIELD_ORDER = ["id", "title", "type", "epic", "service",
               "points", "status", "sprint", "created"]
EDITABLE = {"title", "type", "epic", "service", "points", "status", "sprint"}
ENUMS = {"status": STATUSES, "type": TYPES, "epic": EPICS}


# ------------------------------------------------------------------ ticket io

def split_ticket(path: Path) -> tuple[dict, str]:
    """Return (frontmatter, body). Raises ValueError if malformed."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        raise ValueError(f"{path.name}: no frontmatter")
    parts = text.split("---", 2)
    if len(parts) < 3:
        raise ValueError(f"{path.name}: unterminated frontmatter")
    meta: dict[str, str] = {}
    for line in parts[1].strip().splitlines():
        if ":" in line:
            key, _, value = line.partition(":")
            meta[key.strip()] = value.strip()
    return meta, parts[2].lstrip("\n")


def write_ticket(path: Path, meta: dict, body: str) -> None:
    ordered = [k for k in FIELD_ORDER if k in meta]
    ordered += [k for k in meta if k not in FIELD_ORDER and k != "body"]
    lines = ["---"] + [f"{k}: {meta[k]}" for k in ordered] + ["---", ""]
    path.write_text("\n".join(lines) + body.rstrip("\n") + "\n", encoding="utf-8")


def ticket_path(ticket_id: str) -> Path:
    """Resolve an id to a path, refusing anything that escapes tickets/."""
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]{0,30}", ticket_id):
        raise ValueError(f"bad ticket id {ticket_id!r}")
    path = (TICKETS_DIR / f"{ticket_id}.md").resolve()
    if path.parent != TICKETS_DIR.resolve():
        raise ValueError("path escapes tickets directory")
    if not path.is_file():
        raise FileNotFoundError(f"no such ticket: {ticket_id}")
    return path


def load_tickets() -> tuple[list[dict], list[str]]:
    tickets, problems = [], []
    for path in sorted(TICKETS_DIR.glob("*.md")):
        try:
            meta, _ = split_ticket(path)
        except ValueError as exc:
            problems.append(str(exc))
            continue
        for field in FIELD_ORDER:
            if field not in meta:
                problems.append(f"{path.name}: missing field '{field}'")
        for field, allowed in ENUMS.items():
            if meta.get(field) not in allowed:
                problems.append(f"{path.name}: unknown {field} {meta.get(field)!r}")
        meta["_file"] = path.name
        tickets.append(meta)
    return tickets, problems


# ------------------------------------------------------------------ rendering

def points(ticket: dict) -> int:
    try:
        return int(ticket.get("points", 0))
    except (TypeError, ValueError):
        return 0


def sprint_key(sprint: str) -> tuple[int, str]:
    """Sort unscheduled tickets last."""
    try:
        return (0, f"{int(sprint):03d}")
    except (TypeError, ValueError):
        return (1, "")


def ticket_table(rows: list[dict]) -> list[str]:
    out = ["| ID | Title | Type | Epic | Service | Pts |",
           "|---|---|---|---|---|---|"]
    for t in sorted(rows, key=lambda r: r.get("id", "")):
        out.append(
            f"| [{t.get('id')}](tickets/{t['_file']}) | {t.get('title')} "
            f"| {t.get('type')} | {t.get('epic')} | `{t.get('service')}` "
            f"| {t.get('points')} |"
        )
    return out


def regenerate() -> int:
    tickets, problems = load_tickets()

    lines = ["# Board", "",
             f"_Generated by `tracker/board.py` on {date.today().isoformat()}. "
             "Do not edit by hand._", ""]

    if problems:
        lines += ["## ⚠ Validation problems", ""] + [f"- {p}" for p in problems] + [""]

    if not tickets:
        BOARD_FILE.write_text("\n".join(lines + ["No tickets yet.", ""]), encoding="utf-8")
        print("BOARD.md written (no tickets)")
        return 0

    sprints: dict[str, list[dict]] = {}
    for t in tickets:
        sprints.setdefault(t.get("sprint", "-"), []).append(t)
    ordered = sorted(sprints, key=sprint_key)

    lines += ["## Summary", "",
              "| Sprint | Tickets | Points | Done pts | Remaining pts |",
              "|---|---|---|---|---|"]
    for s in ordered:
        rows = sprints[s]
        total = sum(points(t) for t in rows)
        done = sum(points(t) for t in rows if t.get("status") == "done")
        label = f"Sprint {s}" if s != "-" else "Unscheduled"
        lines.append(f"| {label} | {len(rows)} | {total} | {done} | {total - done} |")
    grand = sum(points(t) for t in tickets)
    grand_done = sum(points(t) for t in tickets if t.get("status") == "done")
    lines += [f"| **All** | **{len(tickets)}** | **{grand}** "
              f"| **{grand_done}** | **{grand - grand_done}** |", ""]

    for s in ordered:
        lines += [f"## {f'Sprint {s}' if s != '-' else 'Unscheduled backlog'}", ""]
        for status in STATUSES:
            rows = [t for t in sprints[s] if t.get("status") == status]
            if not rows:
                continue
            pts = sum(points(t) for t in rows)
            lines += [f"### {status} — {len(rows)} ticket(s), {pts} pt(s)", ""]
            lines += ticket_table(rows) + [""]

    BOARD_FILE.write_text("\n".join(lines), encoding="utf-8")
    print(f"BOARD.md written: {len(tickets)} tickets, {grand} points")
    if problems:
        print(f"{len(problems)} validation problem(s) - see BOARD.md", file=sys.stderr)
    return 0


# ------------------------------------------------------------------ cli

def set_field(ticket_id: str, field: str, value: str) -> int:
    if field not in EDITABLE:
        print(f"'{field}' is not editable. Editable: {', '.join(sorted(EDITABLE))}",
              file=sys.stderr)
        return 2
    if field in ENUMS and value not in ENUMS[field]:
        print(f"invalid {field} {value!r}. Allowed: {', '.join(ENUMS[field])}",
              file=sys.stderr)
        return 2
    try:
        path = ticket_path(ticket_id)
        meta, body = split_ticket(path)
    except (ValueError, FileNotFoundError) as exc:
        print(exc, file=sys.stderr)
        return 2

    before = meta.get(field, "-")
    if before == value:
        print(f"{ticket_id}: {field} already {value}")
        return 0
    meta[field] = value
    write_ticket(path, meta, body)
    print(f"{ticket_id}: {field} {before} → {value}")
    return regenerate()


def list_tickets(status: str | None) -> int:
    if status and status not in STATUSES:
        print(f"invalid status {status!r}. Allowed: {', '.join(STATUSES)}", file=sys.stderr)
        return 2
    tickets, _ = load_tickets()
    rows = [t for t in tickets if not status or t.get("status") == status]
    if not rows:
        print("no matching tickets")
        return 0
    width = max(len(t.get("title", "")) for t in rows)
    for t in sorted(rows, key=lambda r: (sprint_key(r.get("sprint", "-")), r.get("id", ""))):
        print(f"{t.get('id'):<8} {t.get('status'):<12} {t.get('title'):<{width}}  "
              f"{t.get('points'):>2}pt  s{t.get('sprint')}  {t.get('epic')}")
    print(f"\n{len(rows)} ticket(s), {sum(points(t) for t in rows)} point(s)")
    return 0


def main(argv: list[str]) -> int:
    if not TICKETS_DIR.is_dir():
        print(f"no tickets directory at {TICKETS_DIR}", file=sys.stderr)
        return 1

    if not argv:
        return regenerate()

    command, *rest = argv
    if command == "status" and len(rest) == 2:
        return set_field(rest[0], "status", rest[1])
    if command == "set" and len(rest) == 3:
        return set_field(rest[0], rest[1], rest[2])
    if command == "ls" and len(rest) <= 1:
        return list_tickets(rest[0] if rest else None)

    print(__doc__.strip(), file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
